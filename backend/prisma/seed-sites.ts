async function main() {
  const seen = new Set<string>();
  const toCreate: Array<{ siteCode: string; ttkv: string }> = [];

  for (const line of RAW.split('\n')) {
    const parts = line.split('\t');
    if (parts.length < 2) continue;

    const ttkv = parts[0].trim();
    // Clean: remove trailing dots, normalize spaces
    const siteCode = parts[1].trim().replace(/\.+$/, '').replace(/\s+/g, ' ').trim();

    if (!ttkv || !siteCode) continue;
    if (seen.has(siteCode)) continue; // first occurrence wins
    seen.add(siteCode);

    toCreate.push({ siteCode, ttkv });
  }

  console.log(`Parsed ${toCreate.length} unique sites. Upserting...`);

  let done = 0;
  for (const { siteCode, ttkv } of toCreate) {
    const ttkvName = TTKV_NAME[ttkv] || ttkv;
    const prefix   = siteCode.startsWith('SGN') ? 'SGN' : 'HCM';
    const province = 'TP. Hồ Chí Minh';
    const ttkvCode = ttkv || null;

    await prisma.site.upsert({
      where: { siteCode },
      create: {
        siteCode,
        siteName:  `Trạm ${siteCode}`,
        province,
        district:  ttkvName,
        ttkvCode,
        siteType:  prefix === 'SGN' ? 'NodeB' : 'eNodeB',
        active:    true,
      },
      update: {
        ttkvCode,
        district: ttkvName,
      },
    });
    done++;
    if (done % 100 === 0) process.stdout.write(`  ${done}/${toCreate.length}\r`);
  }

  console.log(`\nDone: ${done} sites upserted.`);
}

main()
  .catch((e) => { console.error(e); process.exit(1); })
  .finally(() => prisma.$disconnect());
